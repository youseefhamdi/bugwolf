def generate(target: FuzzTarget) -> FuzzHarness:
    """Generate a fuzz harness for the given target."""
    if target.engine not in _DISPATCH:
        raise ValueError(
            f"unknown engine: {target.engine}; "
            f"supported: {', '.join(_DISPATCH.keys())}"
        )
    harness = _DISPATCH[target.engine](target)
    harness.manifest = {
        "schema": SCHEMA,
        "target": target.name,
        "engine": target.engine,
        "language": target.language,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "file_count": len(harness.files),
        "operators": {
            "build": "cd <output> && ./build.sh",
            "run": "cd <output> && ./run.sh",
            "stop_signal": "SIGINT (Ctrl-C) or process kill",
        },
    }
    return harness


def write(harness: FuzzHarness, output_dir: Path) -> Dict[str, Any]:
    """Write the harness files to ``output_dir``. Returns the manifest."""
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    for rel, content in harness.files.items():
        target = output_dir / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        if rel.endswith(".sh"):
            target.write_text(content)
            target.chmod(0o755)
        else:
            target.write_text(content)
    manifest_path = output_dir / "manifest.json"
    manifest_path.write_text(json.dumps(harness.manifest, indent=2))
    return harness.manifest


