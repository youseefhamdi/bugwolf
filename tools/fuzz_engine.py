def _libfuzzer(target: FuzzTarget) -> FuzzHarness:
    files: Dict[str, str] = {}
    if target.language in ("c", "cpp"):
        files["harness.c"] = LIBFUZZER_C
        files["build.sh"] = (
            "#!/usr/bin/env bash\n"
            "set -euo pipefail\n"
            "clang -fsanitize=fuzzer,address -g harness.c -o harness\n"
        )
    elif target.language == "rust":
        files["src/fuzz_target.rs"] = LIBFUZZER_RUST.replace("<NAME>", target.name)
        files["Cargo.toml"] = textwrap.dedent('''\
            [package]
            name = "fuzz-target"
            version = "0.0.0"
            edition = "2021"

            [dependencies]
            libfuzzer-sys = "0.4"

            [[bin]]
            name = "fuzz_target"
            path = "src/fuzz_target.rs"
        ''')
        files["build.sh"] = (
            "#!/usr/bin/env bash\n"
            "set -euo pipefail\n"
            "rustc -C link-arg=-fsanitize=fuzzer \\\n"
            "      -C passes='sancov' \\\n"
            "      src/fuzz_target.rs -o fuzz_target\n"
        )
    files["run.sh"] = (
        "#!/usr/bin/env bash\n"
        "set -euo pipefail\n"
        "mkdir -p crashes\n"
        "./harness corpus/ -artifact_prefix=crashes/ "
        "-max_len=4096 -timeout=5\n"
    )
    files["corpus/.gitkeep"] = ""
    files["crashes/.gitkeep"] = ""
    return FuzzHarness(target=target.name, engine=target.engine, files=files)


