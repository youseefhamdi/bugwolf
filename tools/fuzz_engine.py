#!/usr/bin/env python3
"""BugWolf fuzz engine v1.24.1+ — coverage-guided fuzzing harness generator.

Generates ready-to-run harnesses for:
  - libFuzzer (LLVM)         → C/C++/Rust targets
  - AFL++                    → C/C++ targets with AFL instrumentation
  - Honggfuzz                → C/C++/Rust targets
  - Python atheris           → Python targets
  - Boofuzz                  → network protocol targets (block-based)
  - Schemathesis             → OpenAPI/GraphQL schema fuzzing
  - foundry fuzz             → Solidity invariants
  - Echidna                  → Solidity properties

The generator does NOT run the fuzzer itself — it scaffolds the harness
and the build script. Operators run the actual fuzzer outside BugWolf.

Usage:
  python3 tools/fuzz_engine.py --target some-target --lang rust \
      --entry-fn fuzz_target --output fuzz/
  python3 tools/fuzz_engine.py --target some-target --engine schemathesis \
      --spec openapi.json --output fuzz/
  python3 tools/fuzz_engine.py --target some-contract --engine foundry \
      --contract Contract.sol --output fuzz/

Each generated harness ships with:
  - The source file (or build instructions)
  - corpus/ seed inputs
  - crash/ output dir
  - run.sh that operators invoke after `cargo install` / `pip install`
  - a JSONL evidence file the mission_runner can read back

This module is offline-by-design: no network, no LLM. It only writes files.
"""
