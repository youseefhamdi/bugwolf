def main() -> int:
    import argparse
    p = argparse.ArgumentParser(description="BugWolf fuzz harness generator")
    p.add_argument("--target", required=True, help="Target name")
    p.add_argument("--engine", required=True, choices=list(ENGINES.keys()),
                   help="Fuzzing engine")
    p.add_argument("--lang", choices=sorted(LANGUAGES), help="Source language")
    p.add_argument("--entry", help="Entry function (e.g. LLVMFuzzerTestOneInput)")
    p.add_argument("--source", help="Source file path (informational)")
    p.add_argument("--contract", help="Solidity contract (for foundry/echidna)")
    p.add_argument("--spec", help="OpenAPI spec path (for schemathesis)")
    p.add_argument("--output", required=True, help="Output directory")
    p.add_argument("--seed", action="append", default=[],
                   help="Path to a seed corpus file (repeatable)")
    args = p.parse_args()

    target = FuzzTarget(
        name=args.target,
        engine=args.engine,
        language=args.lang or _infer_lang(args),
        entry=args.entry,
        source=args.source,
        contract=args.contract,
        spec=args.spec,
        seeds=args.seed,
    )
    harness = generate(target)
    manifest = write(harness, Path(args.output))
    print(f"[+] Fuzz harness written to {args.output}/")
    print(f"    target={target.name} engine={target.engine} "
          f"language={target.language}")
    print(f"    files={len(harness.files)}")
    print(f"    build: cd {args.output} && ./build.sh")
    print(f"    run:   cd {args.output} && ./run.sh")
    return 0


def _infer_lang(args) -> str:
    if args.contract: return "solidity"
    if args.spec: return "python"
    if args.source:
        ext = Path(args.source).suffix.lower()
        if ext in (".rs",): return "rust"
        if ext in (".c", ".h"): return "c"
        if ext in (".cpp", ".cc", ".hpp"): return "cpp"
        if ext in (".py",): return "python"
        if ext in (".sol",): return "solidity"
        if ext in (".go",): return "go"
    return "c"


if __name__ == "__main__":
    raise SystemExit(main())
